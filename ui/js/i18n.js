function applyGlobalLanguage(langCode) {
  const code = langCode || localStorage.getItem('visstya_language') || 'en-US';
  const dict = VISSTYA_DICTIONARY[code];

  if (!dict) return; // Fallback to original HTML text (en-US)

  // 1. Translate elements with direct text matches or data-i18n attribute
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, null, false);
  let node;
  while ((node = walker.nextNode())) {
    const parent = node.parentElement;
    if (parent && (parent.tagName === 'SCRIPT' || parent.tagName === 'STYLE')) continue;
    
    const trimmed = node.nodeValue.trim();
    if (dict[trimmed]) {
      node.nodeValue = node.nodeValue.replace(trimmed, dict[trimmed]);
    }
  }

  // 2. Translate placeholders
  document.querySelectorAll('input[placeholder]').forEach(input => {
    const ph = input.getAttribute('placeholder').trim();
    if (dict[ph]) {
      input.setAttribute('placeholder', dict[ph]);
    }
  });

  // 3. Set html lang attribute
  document.documentElement.lang = code.split('-')[0];
}

document.addEventListener('DOMContentLoaded', () => {
  applyGlobalLanguage();
});

// Expose globally so settings page can call it instantly on dropdown change
window.applyGlobalLanguage = applyGlobalLanguage;
